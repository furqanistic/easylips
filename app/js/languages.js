EasyLips.LANGUAGES = EasyLips.SUPPORTED_LANGUAGES.map((language) => language.label);

EasyLips.getLanguageCode = function getLanguageCode(label) {
  const language = EasyLips.SUPPORTED_LANGUAGES.find((item) => item.label === label);
  return language?.code || null;
};

EasyLips.getLanguageByCode = function getLanguageByCode(code) {
  return EasyLips.SUPPORTED_LANGUAGES.find(
    (language) =>
      language.code === code || language.alternateCodes?.includes(code),
  ) || null;
};
